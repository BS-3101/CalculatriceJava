    private void btnEgalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEgalActionPerformed
    String texte = txtDisplay.getText();

String deuxiemePartie = texte.substring(texte.lastIndexOf(" ") + 1);

double deuxiemeNombre = Double.parseDouble(deuxiemePartie);

double resultat = 0;

switch (operateur) {
    case "+":
        resultat = premierNombre + deuxiemeNombre;
        break;

    case "-":
        resultat = premierNombre - deuxiemeNombre;
        break;

    case "*":
        resultat = premierNombre * deuxiemeNombre;
        break;

    case "/":
        if (deuxiemeNombre == 0) {
            txtDisplay.setText("Erreur");
            return;
        }
        resultat = premierNombre / deuxiemeNombre;
        break;
}

//txtDisplay.setText(String.valueOf(resultat));
if (resultat == (long) resultat) {
    txtDisplay.setText(String.valueOf((long) resultat));
} else {
    txtDisplay.setText(String.valueOf(resultat));
}
    }//GEN-LAST:event_btnEgalActionPerformed

