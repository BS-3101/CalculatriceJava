    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
      String texte = txtDisplay.getText();

int dernierePositionOperateur = -1;

if (texte.contains(" + ")) {
    dernierePositionOperateur = texte.lastIndexOf(" + ");
} else if (texte.contains(" - ")) {
    dernierePositionOperateur = texte.lastIndexOf(" - ");
} else if (texte.contains(" * ")) {
    dernierePositionOperateur = texte.lastIndexOf(" * ");
} else if (texte.contains(" / ")) {
    dernierePositionOperateur = texte.lastIndexOf(" / ");
}

String nombreActuel;

if (dernierePositionOperateur != -1) {
    nombreActuel = texte.substring(dernierePositionOperateur + 3);
} else {
    nombreActuel = texte;
}

if (!nombreActuel.contains(".")) {
    txtDisplay.setText(texte + ".");
}
    }//GEN-LAST:event_jButton2ActionPerformed

